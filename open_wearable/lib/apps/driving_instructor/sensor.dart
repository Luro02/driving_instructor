/// This class contains all the data provided by the IMU.
///
/// It is simpler to bundle them in one class instead of having multiple
/// streams for each sensor.
class SensorStatus {
  Vector3 accelerometer = Vector3(0.0, 0.0, 0.0);
  Vector3 gyroscope = Vector3(0.0, 0.0, 0.0);
  Vector3 euler = Vector3(0.0, 0.0, 0.0);

  DateTime timestamp = DateTime.now();

  double get ax => accelerometer.x;
  double get ay => accelerometer.y;
  double get az => accelerometer.z;

  double get gx => gyroscope.x;
  double get gy => gyroscope.y;
  double get gz => gyroscope.z;

  set ax(double value) => accelerometer.x = value;
  set ay(double value) => accelerometer.y = value;
  set az(double value) => accelerometer.z = value;

  set gx(double value) => gyroscope.x = value;
  set gy(double value) => gyroscope.y = value;
  set gz(double value) => gyroscope.z = value;
}

bool _isCloserToTarget(double value, double target, double bestSoFar) {
  return (value - target).abs() < (bestSoFar - target).abs();
}

abstract class SensorTracker {
  Future<void> calibrate({
    Duration targetDuration = const Duration(milliseconds: 500),
  });

  // TODO: It might be better to refactor streamGyroStatus to return a Vector3?
  Stream<SensorStatus> streamStatus();

  Stream<SensorStatus> streamGyroStatus();
}

class EsenseSensorTracker implements SensorTracker {
  final SensorManager manager;
  final List<EsenseSensorWrapper> _sensors = [];

  Vector3 gyroOffsets = Vector3.zero();

  EsenseSensorTracker({
    required this.manager,
    required double targetFrequencyHz,
  }) {
    for (var sensor in manager.sensors) {
      if (!["accelerometer", "gyroscope"]
          .contains(sensor.sensorName.toLowerCase())) {
        print("Skipping sensor: ${sensor.sensorName}");
        continue;
      }

      _sensors.add(
        EsenseSensorWrapper(
          sensor: sensor,
          samplingFrequencyHz: targetFrequencyHz,
        ),
      );
    }
  }

  @override
  Future<void> calibrate({
    Duration targetDuration = const Duration(milliseconds: 100),
  }) async {
    List<SensorStatus> samples = [];

    // first reset the current offsets
    gyroOffsets = Vector3.zero();
    var subscription = streamGyroStatus().listen((status) {
      samples.add(status);
    });

    await Future.delayed(targetDuration);
    await subscription.cancel();

    // Calculate gyroscope offsets:
    gyroOffsets = samples.map((event) => event.gyroscope).average();

    print("Calibration complete:");
    print("Gyro offsets: $gyroOffsets");
  }

  @override
  Stream<SensorStatus> streamStatus() {
    StreamController<SensorStatus> controller =
        StreamController<SensorStatus>();
    List<StreamSubscription<SensorValue>> subscriptions = [];

    // The API provides a separate stream for each sensor, and instead of considering
    // the IMU (accelerometer + gyroscope) as a single unit they are separate.
    //
    // Technically this is only the case in the API, the actual communication returns
    // them as a single stream of data packets containing both accelerometer and gyroscope
    // data.
    //
    // It is inconvenient to have them separate. This code combines the streams into a single
    // stream of SensorStatus updates.
    //
    // It is not possible to simply merge sensor values with the same timestamp:
    //
    // The timestamps are generated by the API and not the sensor itself. They start at point
    // x in time, then add 1 / sampling_frequency for each sample and that is the timestamp.
    //
    // This would be fine if both sensors tracked their timestamps independently of each other,
    // but they don't. Instead, both sensors share the same timestamp counter, messing up the
    // actual time between samples and making it impossible to simply merge samples with the same
    // timestamp.
    //
    // Thankfully when you listen to both sensors simultaneously, the API returns samples in the correct order,
    // and roughly equal amounts of samples are obtained from both sensors over time.
    //
    // The below code merges them by only emitting a SensorStatus for new gyroscope data, and copying over
    // the last accelerometer data received.

    for (var sensor in _sensors) {
      SensorStatus lastAccelStatus = SensorStatus();
      var sub = sensor.sensorStream.listen((sensorValue) {
        SensorStatus status = SensorStatus();
        switch (sensor.sensorName.toLowerCase()) {
          case "accelerometer":
            lastAccelStatus.ax = sensorValue.values[0];
            lastAccelStatus.ay = sensorValue.values[1];
            lastAccelStatus.az = sensorValue.values[2];
            return; // Don't emit accelerometer data yet
          case "gyroscope":
            status.gx = sensorValue.values[0] - gyroOffsets.x;
            status.gy = sensorValue.values[1] - gyroOffsets.y;
            status.gz = sensorValue.values[2] - gyroOffsets.z;
            break;
          default: // Ignore unknown sensors
            return;
        }

        // Copy over last accelerometer data
        status.ax = lastAccelStatus.ax;
        status.ay = lastAccelStatus.ay;
        status.az = lastAccelStatus.az;

        status.timestamp = DateTime.now();

        controller.add(status);
      });
      subscriptions.add(sub);
    }

    controller.onCancel = () {
      for (var sub in subscriptions) {
        sub.cancel();
      }
    };

    return controller.stream;
  }

  @override
  Stream<SensorStatus> streamGyroStatus() {
    for (var sensor in _sensors) {
      if (sensor.sensorName.toLowerCase() != "gyroscope") {
        continue;
      }

      return sensor.sensorStream.map((sensorValue) {
        SensorStatus status = SensorStatus();
        status.gx = sensorValue.values[0] - gyroOffsets.x;
        status.gy = sensorValue.values[1] - gyroOffsets.y;
        status.gz = sensorValue.values[2] - gyroOffsets.z;
        status.timestamp = DateTime.now();

        return status;
      });
    }

    throw Exception("No gyroscope sensor found");
  }
}

class SensorDelegator<SV extends SensorValue> implements Sensor<SV> {
  final Sensor sensor;

  SensorDelegator({required this.sensor});

  @override
  String get sensorName => sensor.sensorName;

  @override
  String get chartTitle => sensor.chartTitle;

  @override
  String get shortChartTitle => sensor.shortChartTitle;

  @override
  List<SensorConfiguration> get relatedConfigurations =>
      sensor.relatedConfigurations;

  @override
  int get timestampExponent => sensor.timestampExponent;

  @override
  List<String> get axisNames => sensor.axisNames;

  @override
  List<String> get axisUnits => sensor.axisUnits;

  @override
  int get axisCount => sensor.axisCount;

  /// A stream of sensor values that emits new values as they are received.
  /// In order to use this stream, the sensor must be started using the
  /// [relatedConfigurations].
  @override
  Stream<SV> get sensorStream => sensor.sensorStream as Stream<SV>;
}

class EsenseSensorWrapper extends SensorDelegator<SensorDoubleValue> {
  final DateTime now = DateTime.now();
  final double samplingFrequencyHz;
  late final double actualSamplingFrequencyHz;

  EsenseSensorWrapper({
    required super.sensor,
    required this.samplingFrequencyHz,
  }) {
    for (var config in sensor.relatedConfigurations) {
      if (config is SensorFrequencyConfiguration) {
        actualSamplingFrequencyHz =
            _configureSensor(config, samplingFrequencyHz);
        break;
      }
    }
  }

  @override
  List<String> get axisUnits => switch (sensor.sensorName.toLowerCase()) {
        "accelerometer" => ["m/s²", "m/s²", "m/s²"],
        _ => super.axisUnits,
      };

  Duration timestampDuration(int timestamp) {
    double inSeconds = timestamp * pow(10, timestampExponent).toDouble();

    int seconds = inSeconds.floor();
    int microseconds =
        ((inSeconds - seconds) * Duration.microsecondsPerSecond).round();

    return Duration(
      seconds: seconds,
      microseconds: microseconds,
    );
  }

  double _configureSensor(
    SensorFrequencyConfiguration config,
    double targetFrequencyHz,
  ) {
    SensorFrequencyConfigurationValue? desiredConfig;
    for (var value in config.values) {
      // This seems like the best way to skip the "off" values, given
      // that config.offValue is always null
      if (value.toString().contains("off")) {
        continue;
      }

      if (desiredConfig == null ||
          _isCloserToTarget(
            value.frequencyHz,
            targetFrequencyHz,
            desiredConfig.frequencyHz,
          )) {
        desiredConfig = value;
      }
    }

    config.setConfiguration(desiredConfig!);

    return desiredConfig.frequencyHz;
  }

  @override
  Stream<SensorDoubleValue> get sensorStream {
    final errorMeasure = {
      "accelerometer": 5.0,
      "gyroscope": 10.0,
    };

    var filters = errorMeasure.map(
      (name, errorMeasure) => MapEntry(
        name,
        List.generate(
          3,
          (i) => SimpleKalman(
            errorMeasure: errorMeasure,
            errorEstimate: errorMeasure,
            q: 0.9,
          ),
        ),
      ),
    );

    switch (sensor.sensorName.toLowerCase()) {
      case "accelerometer":
        return super.sensorStream.map((event) {
          for (var i = 0; i < 3; i++) {
            event.values[i] =
                filters["accelerometer"]![i].filtered(event.values[i]);
          }

          var convertedValues =
              event.values.map((v) => v * 9.80665).toList(growable: false);
          return SensorDoubleValue(
            values: convertedValues,
            timestamp: event.timestamp,
          );
        });
      case "gyroscope":
        return super.sensorStream.map((event) {
          for (var i = 0; i < 3; i++) {
            event.values[i] =
                filters["gyroscope"]![i].filtered(event.values[i]);
          }
          return event;
        }).rollingAverage((samplingFrequencyHz * 0.5).toInt());
      default:
        return super.sensorStream;
    }
  }
}
